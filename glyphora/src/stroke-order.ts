export function strokeSteps(g: Glyph): string[] {
  if (g.paths)
    return g.paths.map((_, i) => `第 ${i + 1} 笔：沿高亮轨迹，从圆点起笔，跟随动画方向书写。`);
  return (
    (g.language === 'ru'
      ? g.group === 'upper'
        ? upper
        : ruLower
      : g.group === 'upper'
        ? greekUpper
        : greekLower)[g.text] ?? []
  );
}
